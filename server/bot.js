function getRandomItem(array) {
  return array[Math.floor(Math.random() * array.length)];
}

function processMessage(text) {
  if (!text || typeof text !== 'string') {
    return { reply: 'Пожалуйста, введите ваш вопрос.', intent: 'error' };
  }

  const trimmed = text.trim();

  if (trimmed.length === 0) {
    return { reply: 'Пожалуйста, введите ваш вопрос.', intent: 'empty' };
  }

  if (trimmed.length > 1000) {
    return { reply: 'Сообщение слишком длинное. Пожалуйста, сократите его.', intent: 'too_long' };
  }

  for (const [intent, config] of Object.entries(responses)) {
    for (const pattern of config.patterns) {
      if (pattern.test(trimmed)) {
        return {
          reply: getRandomItem(config.replies),
          intent
        };
      }
    }
  }

  return {
    reply: getRandomItem(fallbackReplies),
    intent: 'fallback'
  };
}

module.exports = { processMessage };
